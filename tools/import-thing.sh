#!/usr/bin/env bash
# Import or update a Thingiverse "Download All Files" ZIP into a product folder.
#
# Usage: tools/import-thing.sh <thing.zip> <product-dir> [slug]
#
#   tools/import-thing.sh ~/Downloads/"RB-02 Avionics SixPack Box 80mm - 7088576.zip" RB-02
#
# Creates <product-dir>/<slug>-<thing-id>/ with files/, images/ and a README.md
# built from the export's README.txt, which is then deleted. Designs by the
# authors in RB_OWNERS (default XIAPROJECTS) fall under the repo LICENSE.md and
# the Thingiverse LICENSE.txt is dropped; any other author's LICENSE.txt is kept.
# The slug defaults to the Thing title without "RB-0x" and the word "Avionics".
#
# A Thing ID that already has a folder is updated in place: files/ and images/
# are replaced and only the generated parts block of README.md is rewritten;
# the Thingiverse summary is printed so the description can be compared by hand.
set -euo pipefail

usage() { sed -n '2,16p' "$0" | sed -E 's/^# ?//' >&2; exit 2; }
owners=" ${RB_OWNERS:-XIAPROJECTS} "
[ $# -eq 2 ] || [ $# -eq 3 ] || usage
zip=$1 product=${2%/} slug=${3:-}

die() { echo "error: $*" >&2; exit 1; }
[ -f "$zip" ] || die "no such file: $zip"
[ -d "$product" ] || die "product folder not found: $product"

# Archives are untrusted: refuse absolute paths, ".." and symlinks before extracting.
# (grep without -q reads all input, so pipefail never sees a SIGPIPE from unzip.)
unzip -Z1 "$zip" | grep -E '(^/|(^|/)\.\.(/|$))' >/dev/null && die "unsafe path in $zip"
unzip -Z "$zip" | grep '^l' >/dev/null && die "symlink in $zip"

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
unzip -q "$zip" -d "$tmp/zip"
[ -f "$tmp/zip/README.txt" ] || die "no README.txt in $zip: not a Thingiverse export?"

# First line: "<title> by <author> on Thingiverse: https://www.thingiverse.com/thing:<id>"
header=$(head -n1 "$tmp/zip/README.txt" | tr -d '\r')
id=$(sed -nE 's|.*thingiverse\.com/thing:([0-9]+).*|\1|p' <<<"$header")
title=$(sed -nE 's/^(.*) by .* on Thingiverse:.*/\1/p' <<<"$header")
author=$(sed -nE 's/^.* by (.*) on Thingiverse:.*/\1/p' <<<"$header")
[ -n "$id" ] && [ -n "$title" ] || die "cannot parse README.txt header: $header"

slugify() {
  tr '[:upper:]' '[:lower:]' |
    sed -E 's/^rb-?[0-9]+ +//; s/(^| )avionics( |$)/ /g; s/[^a-z0-9]+/-/g; s/^-+//; s/-+$//'
}

existing=$(find "$product" -mindepth 1 -maxdepth 1 -type d -name "*-$id" | head -n1)
if [ -n "$existing" ]; then
  dest=$existing
  [ -z "$slug" ] || echo "note: thing:$id already lives in $dest, slug ignored" >&2
else
  [ -n "$slug" ] || slug=$(slugify <<<"$title")
  dest=$product/$slug-$id
fi

mkdir -p "$dest"
rm -rf "$dest/files" "$dest/images"
cp -R "$tmp/zip/." "$dest/"
mv "$dest/README.txt" "$tmp/README.txt"

# The repo forbids spaces in paths.
find "$dest" -depth -name '* *' | while IFS= read -r p; do
  mv "$p" "$(dirname "$p")/$(basename "$p" | tr ' ' '_')"
done

if [[ $owners == *" $author "* ]]; then
  rm -f "$dest/LICENSE.txt"
  license="Free for personal use; commercial use requires an agreement, see [LICENSE.md](../../LICENSE.md)"
else
  # "Creative Commons - Attribution - Share Alike" -> "... (CC BY-SA)"
  license=$(sed -nE 's/.*licensed under (.*)/\1/p' "$dest/LICENSE.txt" | tr -d '\r' | head -n1)
  short=$(sed -E 's/^Creative Commons - //; s/Attribution/BY/; s/Non-Commercial/NC/; s/No Derivatives/ND/; s/Share Alike/SA/; s/ - /-/g' <<<"$license")
  if [[ $license == "Creative Commons"* && $short =~ ^(BY|NC|ND|SA)(-(BY|NC|ND|SA))*$ ]]; then
    license="$license (CC $short)"
  fi
  license="$license, see [LICENSE.txt](LICENSE.txt)"
fi
summary=$(awk 'f; /^Summary:/ { f = 1 }' "$tmp/README.txt" | tr -d '\r' |
  sed -E "s/&amp;/\&/g; s/&lt;/</g; s/&gt;/>/g; s/&quot;/\"/g; s/&#39;/'/g")

human_size() {
  awk -v b="$(wc -c <"$1")" 'BEGIN { if (b >= 1048576) printf "%.1f MB", b / 1048576; else printf "%d KB", (b + 1023) / 1024 }'
}

# Parts table: every file in files/, with the Thingiverse render of the same name.
# Images that are not a part render are listed as photos.
declare -A used=()
photos=()
block=$tmp/parts.md
{
  echo "<!-- BEGIN parts: generated by tools/import-thing.sh, do not edit by hand -->"
  echo "## Parts"
  echo
  echo "| File | Size | Preview |"
  echo "|---|---:|---|"
  for f in "$dest"/files/*; do
    [ -f "$f" ] || continue
    name=$(basename "$f")
    preview=""
    for ext in png jpg jpeg; do
      if [ -f "$dest/images/${name%.*}.$ext" ]; then
        preview="<img src=\"images/${name%.*}.$ext\" width=\"160\">"
        used[${name%.*}.$ext]=1
        break
      fi
    done
    echo "| [$name](files/$name) | $(human_size "$f") | $preview |"
  done
  for i in "$dest"/images/*; do
    [ -f "$i" ] || continue
    [ -n "${used[$(basename "$i")]:-}" ] || photos+=("$(basename "$i")")
  done
  if [ ${#photos[@]} -gt 0 ]; then
    echo
    echo "## Photos"
    echo
    for p in "${photos[@]}"; do echo "<img src=\"images/$p\" width=\"320\">"; done
  fi
  echo "<!-- END parts -->"
} >"$block"

readme=$dest/README.md
if [ ! -f "$readme" ]; then
  hero=${photos[0]:-$(find "$dest/images" -maxdepth 1 -type f -printf '%f\n' 2>/dev/null | sort | head -n1)}
  {
    echo "# $title"
    echo
    if [ -n "$hero" ]; then
      echo "![$title](images/$hero)"
      echo
    fi
    echo "| | |"
    echo "|---|---|"
    echo "| Thingiverse | [thing:$id](https://www.thingiverse.com/thing:$id) |"
    echo "| Author | $author |"
    echo "| License | $license |"
    echo
    echo "> **Printing for an aircraft:** the parts must withstand 100 °C in cruise on long flights." \
      "Read [PRINTING.md](../../PRINTING.md) for the materials and the test before printing."
    echo
    echo "## Description"
    echo
    echo "<!-- TODO: Thingiverse drops line breaks from the summary; reformat it. -->"
    echo "$summary"
    echo
    cat "$block"
  } >"$readme"
elif grep -q '^<!-- BEGIN parts' "$readme"; then
  awk -v blk="$block" '
    /^<!-- BEGIN parts/ { while ((getline l < blk) > 0) print l; skip = 1; next }
    /^<!-- END parts/   { skip = 0; next }
    !skip' "$readme" >"$tmp/README.md"
  cat "$tmp/README.md" >"$readme"
  printf 'Thingiverse summary, compare it with README.md by hand:\n%s\n\n' "$summary" >&2
else
  echo "warning: no parts markers in $readme, appending the parts block" >&2
  { echo; cat "$block"; } >>"$readme"
fi

cat <<EOF
Imported thing:$id into $dest
  Title:   $title
  Author:  $author
  License: $license
  Files:   $(find "$dest" -path "$dest/files/*" -type f | wc -l)
Next: reformat the description in a new README.md, add or update the design
in README.md and $product/README.md, run tools/check.sh, delete the ZIP.
EOF
